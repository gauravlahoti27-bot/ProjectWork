"""AI Career Assistant.

Works out of the box with a data-aware, rule-based engine (searches the portal's own
jobs / events / alumni / campaigns). If OPENAI_API_KEY is set, answers are generated by
OpenAI using the same portal data as context, with automatic fallback to the rule engine.
"""
import re
from datetime import date

from flask import Blueprint, current_app, g, jsonify, render_template, request

from database import execute, query
from utils import like, login_required, pretty_date

chatbot_bp = Blueprint("chatbot", __name__)

STOP = set("a an the i me my to for of in on at is are am be and or with about can you please show find tell any some what who how when where do does want need looking help get give list".split())


def _keywords(text):
    return [w for w in re.findall(r"[a-zA-Z+#.]{2,}", text.lower()) if w not in STOP]


def _link(label, url):
    return {"label": label, "url": url}


def _rule_reply(msg):
    m, kws = msg.lower(), _keywords(msg)
    links = []

    if re.search(r"\b(hi|hello|hey|namaste)\b", m) and len(kws) <= 1:
        return (f"Hi {g.user['full_name'].split()[0]}! 👋 I can find jobs, mentors, upcoming events, "
                "help you improve your profile and tell you about donation campaigns. What do you need?"), []

    if re.search(r"\b(job|jobs|intern|internship|opening|hiring|vacanc|role|career)\w*", m):
        terms = [k for k in kws if k not in ("job", "jobs", "internship", "internships", "intern", "opening", "openings", "hiring", "career", "role", "roles")]
        sql, args = "SELECT * FROM jobs", []
        if terms:
            sql += " WHERE " + " OR ".join("(title LIKE ? ESCAPE '\\' OR company LIKE ? ESCAPE '\\' OR location LIKE ? ESCAPE '\\' OR description LIKE ? ESCAPE '\\')" for _ in terms[:3])
            for t in terms[:3]:
                args += [like(t)] * 4
        if "intern" in m:
            sql += (" AND" if terms else " WHERE") + " job_type = 'Internship'"
        rows = query(sql + " ORDER BY created_at DESC, id DESC LIMIT 5", args)
        if rows:
            lines = [f"• {r['title']} at {r['company']} ({r['location'] or 'n/a'}, {r['job_type']})" for r in rows]
            return "Here are openings that match:\n" + "\n".join(lines), [_link("Browse all jobs", "/jobs")]
        return "I couldn't find a matching opening right now. Try a broader term, or check back soon.", [_link("Browse all jobs", "/jobs")]

    if re.search(r"\b(event|events|meet|reunion|workshop|webinar|session|happening)\w*", m):
        rows = query("SELECT * FROM events WHERE event_date >= ? ORDER BY event_date LIMIT 4", (date.today().isoformat(),))
        if rows:
            lines = [f"• {r['title']} — {pretty_date(r['event_date'])}, {r['venue'] or 'TBA'}" for r in rows]
            return "Upcoming events:\n" + "\n".join(lines), [_link("View & register", "/events")]
        return "No upcoming events right now. Alumni and admins can create one from the Events page.", [_link("Events", "/events")]

    if re.search(r"\b(mentor|mentors|mentorship|guidance|advice|guide|connect|network)\w*", m):
        terms = [k for k in kws if not k.startswith(("mentor", "guid", "advice", "connect", "network"))]
        sql, args = "SELECT * FROM users WHERE open_to_mentor = 1 AND id != ?", [g.user["id"]]
        if terms:
            sql += " AND (" + " OR ".join("(skills LIKE ? ESCAPE '\\' OR company LIKE ? ESCAPE '\\' OR designation LIKE ? ESCAPE '\\' OR branch LIKE ? ESCAPE '\\')" for _ in terms[:3]) + ")"
            for t in terms[:3]:
                args += [like(t)] * 4
        rows = query(sql + " ORDER BY graduation_year DESC LIMIT 4", args)
        if rows:
            lines = [f"• {r['full_name']} — {r['designation'] or 'Alumni'} @ {r['company'] or '—'}" for r in rows]
            return "These alumni are open to mentoring:\n" + "\n".join(lines), \
                [_link(r["full_name"], f"/alumni/{r['id']}") for r in rows]
        return "No mentors matched that. Try the directory filter “Open to mentor”.", [_link("Alumni directory", "/directory?mentors=1")]

    if re.search(r"\b(alumni|alumnus|batch|directory|who works|people)\b", m):
        terms = [k for k in kws if k not in ("alumni", "alumnus", "batch", "directory", "works", "work", "people", "company")]
        if terms:
            t = like(terms[0])
            rows = query("""SELECT * FROM users WHERE role!='admin' AND (company LIKE ? ESCAPE '\\' OR full_name LIKE ? ESCAPE '\\'
                            OR skills LIKE ? ESCAPE '\\' OR location LIKE ? ESCAPE '\\' OR CAST(graduation_year AS TEXT) LIKE ? ESCAPE '\\') LIMIT 5""", [t] * 5)
            if rows:
                return "Found these people:\n" + "\n".join(f"• {r['full_name']} — {r['designation'] or 'Alumni'} @ {r['company'] or '—'} (batch {r['graduation_year']})" for r in rows), \
                    [_link("Open directory", "/directory?q=" + terms[0])]
        return "Use the directory to search by name, company, skill, batch or city.", [_link("Alumni directory", "/directory")]

    if re.search(r"\b(donat|fund|scholarship|give back|contribut|campaign)\w*", m):
        rows = query("""SELECT c.title, c.goal_amount, COALESCE(SUM(d.amount),0) raised FROM campaigns c
                        LEFT JOIN donations d ON d.campaign_id=c.id GROUP BY c.id LIMIT 4""")
        lines = [f"• {r['title']}: ₹{r['raised']:,.0f} of ₹{r['goal_amount']:,.0f}" for r in rows]
        return "Active campaigns:\n" + "\n".join(lines), [_link("Donate", "/donations")]

    if re.search(r"\b(profile|resume|cv|improve|linkedin|skills)\b", m):
        tips = []
        u = g.user
        if not u["bio"]: tips.append("Add a short bio so others know what you do")
        if not u["skills"]: tips.append("List 4–6 skills — they power mentor & job matching")
        if not u["company"]: tips.append("Add your current company / designation")
        if not u["linkedin"]: tips.append("Link your LinkedIn profile")
        if not u["open_to_mentor"] and u["role"] == "alumni": tips.append("Turn on “Open to mentor” to help juniors")
        return ("Profile tips:\n" + "\n".join("• " + t for t in tips)) if tips else "Your profile looks complete — great job! Keep your skills and role up to date.", [_link("Edit profile", "/profile")]

    return ("I can help with jobs, mentors, events, the alumni directory, donations and profile tips. "
            "Try: “internships in Mumbai”, “mentors in python” or “what events are coming up?”"), []


def _llm_reply(msg):
    """Optional OpenAI path; returns None on any failure so the rule engine takes over."""
    key = current_app.config["OPENAI_API_KEY"]
    if not key:
        return None
    try:
        from openai import OpenAI

        jobs = query("SELECT title,company,location,job_type FROM jobs ORDER BY id DESC LIMIT 8")
        events = query("SELECT title,event_date,venue FROM events WHERE event_date >= ? ORDER BY event_date LIMIT 5", (date.today().isoformat(),))
        mentors = query("SELECT full_name,company,designation,skills FROM users WHERE open_to_mentor=1 LIMIT 8")
        ctx = "JOBS: " + "; ".join(f"{j['title']} @ {j['company']} ({j['location']}, {j['job_type']})" for j in jobs)
        ctx += "\nEVENTS: " + "; ".join(f"{e['title']} on {e['event_date']} at {e['venue']}" for e in events)
        ctx += "\nMENTORS: " + "; ".join(f"{m['full_name']} ({m['designation']} @ {m['company']}; {m['skills']})" for m in mentors)
        history = query("SELECT sender, body FROM chat_messages WHERE user_id=? ORDER BY id DESC LIMIT 6", (g.user["id"],))[::-1]
        messages = [{"role": "system", "content": "You are the Alumni Nexus AI career assistant for a college alumni portal. "
                     "Be concise, friendly and practical. Use ONLY this portal data when recommending jobs, events or people.\n" + ctx}]
        messages += [{"role": "user" if h["sender"] == "user" else "assistant", "content": h["body"]} for h in history]
        messages.append({"role": "user", "content": msg})
        resp = OpenAI(api_key=key).chat.completions.create(model=current_app.config["OPENAI_MODEL"], messages=messages, max_tokens=400, timeout=15)
        return resp.choices[0].message.content.strip()
    except Exception:  # network, quota, missing package…
        return None


@chatbot_bp.route("/chatbot")
@login_required
def chatbot():
    history = query("SELECT sender, body FROM chat_messages WHERE user_id=? ORDER BY id DESC LIMIT 30", (g.user["id"],))[::-1]
    return render_template("chatbot.html", history=history, ai_enabled=bool(current_app.config["OPENAI_API_KEY"]))


@chatbot_bp.route("/ask", methods=["POST"])
@login_required
def ask():
    message = ((request.get_json(silent=True) or {}).get("message") or "").strip()[:500]
    if not message:
        return jsonify(error="Please type a message."), 400
    reply, links = _rule_reply(message)
    llm = _llm_reply(message)
    if llm:
        reply = llm
    execute("INSERT INTO chat_messages (user_id,sender,body) VALUES (?,?,?)", (g.user["id"], "user", message))
    execute("INSERT INTO chat_messages (user_id,sender,body) VALUES (?,?,?)", (g.user["id"], "bot", reply))
    return jsonify(reply=reply, links=links)


@chatbot_bp.route("/chatbot/clear", methods=["POST"])
@login_required
def clear():
    execute("DELETE FROM chat_messages WHERE user_id=?", (g.user["id"],))
    return jsonify(ok=True)
